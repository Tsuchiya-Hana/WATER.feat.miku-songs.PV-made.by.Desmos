# -*- coding: utf-8 -*-
import os
p = os.path.join(os.path.dirname(__file__), '..', 'src', 'data.js')
s = open(p, encoding='utf-8').read()
s = s.replace('// generated by tools/gen_data.py — do not edit by hand', '// generated data for WATER MV\nwindow.WATER_DATA = {};')
s = s.replace('export const CUES =', 'WATER_DATA.CUES =')
s = s.replace('export const SHOTS =', 'WATER_DATA.SHOTS =')
s = s.replace('export const IMPACTS =', 'WATER_DATA.IMPACTS =')
open(p, 'w', encoding='utf-8').write(s)
print('ok')
